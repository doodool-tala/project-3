// Returns the zero-based wheel index for a manual key/drawbar, or -1 when the
// entry is not wired.
inline int wiredWheel(int keyIndex, int drawbarIndex) {
  if (keyIndex < 0 || keyIndex >= kWiringKeys || drawbarIndex < 0 ||
      drawbarIndex >= kWiringDrawbars) {
    return -1;
  }
  const int wheel = kManualWiring[keyIndex][drawbarIndex];
  if (wheel < 1 || wheel > 91) return -1;
  return wheel - 1;
}

